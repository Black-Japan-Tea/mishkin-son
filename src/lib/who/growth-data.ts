export function seriesAt(series: GrowthSeries, month: number): { median: number; sd: number } {
  const i = Math.min(Math.max(Math.round(month), 0), series.median.length - 1);
  const median = series.median[i];
  const sd = series.sd[i];
  if (median === undefined || sd === undefined) {
    return { median: series.median[series.median.length - 1] ?? 0, sd: series.sd[0] ?? 1 };
  }
  return { median, sd };
}
