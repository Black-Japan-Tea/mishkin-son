/** Цвета графиков ECharts: оси/подписи зависят от темы, серии — константы бренда. */

export interface ChartPalette {
  /** Основной текст (тултип, лейблы ИТОГО) */
  text: string;
  /** Средний текст (легенда) */
  t2: string;
  /** Третичный текст (подписи осей, markLine/markArea) */
  t3: string;
  /** Сеточные линии и оси */
  split: string;
  /** Фон тултипа */
  tip: string;
}

/** Светлая тема: чернильный текст на светлом стекле; тёмная — наоборот. */
export function palette(dark: boolean): ChartPalette {
  return dark
    ? { text: "#F3F6FA", t2: "rgba(243,246,250,.62)", t3: "rgba(243,246,250,.38)", split: "rgba(255,255,255,.08)", tip: "#1A2028" }
    : { text: "#0B0E12", t2: "rgba(11,14,18,.62)", t3: "rgba(11,14,18,.38)", split: "rgba(11,14,18,.07)", tip: "#FFFFFF" };
}

/** Серийные цвета — одинаковы в обеих темах (как токены --sleep/--food волны 0). */
